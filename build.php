<?php
declare(strict_types=1);


$root = __DIR__;
$srcDir = $root . '/src';
$outFile = $srcDir . '/build-info.php';

if (!is_dir($srcDir)) {
    fwrite(STDERR, "ERROR: Jalankan dari root repo (folder src/ tidak ditemukan).\n");
    exit(1);
}

function run_git(string $args, string $cwd): array
{
    $desc = [1 => ['pipe', 'w'], 2 => ['pipe', 'w']];
    $proc = @proc_open('git ' . $args, $desc, $pipes, $cwd);
    if (!is_resource($proc)) {
        return ['', 1];
    }
    $stdout = stream_get_contents($pipes[1]);
    fclose($pipes[1]);
    fclose($pipes[2]);
    $code = proc_close($proc);
    return [trim((string) $stdout), $code];
}

[$hash, $hCode] = run_git('rev-parse --short HEAD', $root);
if ($hCode !== 0 || $hash === '') {
    fwrite(STDERR, "ERROR: Bukan git repo, atau git tidak terpasang.\n");
    exit(1);
}

[$branch] = run_git('rev-parse --abbrev-ref HEAD', $root);
[$status] = run_git('status --porcelain', $root);

$dirty     = $status !== '';
$timestamp = date('c');

$info = [
    'hash'      => $hash,
    'branch'    => $branch !== '' ? $branch : 'unknown',
    'timestamp' => $timestamp,
    'dirty'     => $dirty,
];

$php = "<?php\n"
     . "// Auto-generated by build.php — DO NOT EDIT\n"
     . "// Generated at: {$timestamp}\n"
     . "return " . var_export($info, true) . ";\n";

if (file_put_contents($outFile, $php) === false) {
    fwrite(STDERR, "ERROR: Gagal menulis {$outFile}\n");
    exit(1);
}

$version = $hash . ($dirty ? '-dirty' : '');

echo "✓ Build OK\n";
echo "  Version : {$version}\n";
echo "  Branch  : {$branch}\n";
echo "  Time    : {$timestamp}\n";
echo "  Output  : {$outFile}\n";
